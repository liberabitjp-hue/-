def assign_units(slots):
    """(日, 校時) -> (教科, 単元名, 進度, 由来)"""
    queues = {k: list(v) for k, v in UNITS.items()}
    # 総合: 米の枠を決める（活動が書かれた枠 + 震災3時間の後の枠）
    sogo = sorted(k for k, (s, _) in slots.items() if s == '総合')
    others = [k for k in sogo if k not in RICE]
    shinsai = set(others[:len(SOGO_SHINSAI)])
    kome = [k for k in sogo if k not in shinsai]
    sogo_units = {}
    for k, u in zip(sorted(shinsai), SOGO_SHINSAI):
        sogo_units[k] = u
    for i, k in enumerate(kome):
        sogo_units[k] = ('本宮の米を全国に発信しよう',
                         '%d/%d' % (SOGO_KOME_START + i, SOGO_KOME_TOTAL))

    out = {}
    for k in sorted(slots):
        sub, origin = slots[k]
        if k in EVENT_UNITS:
            unit, prog = EVENT_UNITS[k]
        elif sub == '総合':
            unit, prog = sogo_units[k]
        elif sub == '家庭':
            unit, prog = KATEI[k], ''
        else:
            q = queues.get(sub)
            if not q:
                raise AssertionError('%s の単元が足りません（%d日%d校時）' % (sub, k[0], k[1]))
            unit, prog = q.pop(0)
        out[k] = (sub, unit, prog, origin)
    left = {k: len(v) for k, v in queues.items() if v}
    if left:
        raise AssertionError('割り当てきれなかった単元があります: %s' % left)
    return out


# --- 通級指導（R8 通級II 固定時間割表 10-12月）で5-2の児童が抜ける枠 ---
TSUKYU = {('火', 2): '国語', ('水', 3): '算数', ('水', 5): '国語', ('金', 2): '算数'}


def check_tsukyu(plan):
    """通級で児童が抜ける枠に、想定した教科が入っているかを点検する。"""
    dow = {d: w for d, w, _ in DAYS}
    ng = []
    for (day, period), (sub, _u, _p, origin) in sorted(plan.items()):
        want = TSUKYU.get((dow[day], period))
        if want and sub != want:
            ng.append('%d日(%s)%d校時: %s［%s］（通級は%sを想定）'
                      % (day, dow[day], period, sub, origin, want))
    return ng


