def assign_units(slots):
    """(日, 校時) -> (教科, 単元名, 進度, 由来)"""
    queues = {k: list(v) for k, v in UNITS.items()}
    out = {}
    for (day, period) in sorted(slots):
        sub, origin = slots[(day, period)]
        if (day, period) in EVENT_UNITS:
            unit, prog = EVENT_UNITS[(day, period)]
        else:
            q = queues.get(sub)
            if not q:
                raise AssertionError('%s の単元が足りません（%d日%d校時）' % (sub, day, period))
            unit, prog = q.pop(0)
        out[(day, period)] = (sub, unit, prog, origin)
    left = {k: len(v) for k, v in queues.items() if v}
    if left:
        raise AssertionError('割り当てきれなかった単元があります: %s' % left)
    return out


def check_tsukyu(plan):
    """通級で児童が抜ける枠に、想定した教科が入っているかを点検する。"""
    dow = {d: w for d, w, _ in DAYS}
    ng = []
    for (day, period), (sub, _unit, _prog, _o) in sorted(plan.items()):
        want = TSUKYU.get((dow[day], period))
        if want and sub != want:
            ng.append('%d日(%s)%d校時: %s（通級は%sを想定）' % (day, dow[day], period, sub, want))
    return ng


