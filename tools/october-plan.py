def build():
    """(日, 校時) -> (教科, 由来) の割当てを返す。"""
    slots = {}
    for day, dow, periods in DAYS:
        for p in range(1, periods + 1):
            if (day, p) in EVENTS:
                slots[(day, p)] = (EVENTS[(day, p)][0], '行事')
            elif (day, p) in BUNKA_FIXED:
                slots[(day, p)] = (BUNKA_FIXED[(day, p)], '分科確定')
            elif (day, p) in ADJUST:
                slots[(day, p)] = (ADJUST[(day, p)][0], '調整')
            else:
                sub = BASE[dow][p - 1]
                if sub is None:
                    raise AssertionError('%d日%d校時に基本パターンがありません' % (day, p))
                if sub == '外国語':
                    raise AssertionError(
                        '%d日%d校時は分科資料に5-2外国語の割当てが無い。調整表で埋めること' % (day, p))
                bunka = sub in ('理科', '外国語', '書写') or (dow == '金' and p in (3, 4))
                slots[(day, p)] = (sub, '分科' if bunka else '前月パターン')
    return slots


def tally(slots):
    counts = {}
    for sub, _ in slots.values():
        counts[sub] = counts.get(sub, 0) + 1
    return counts


