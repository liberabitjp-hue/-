def build():
    """(日, 校時) -> (教科, 由来) の割当てを返す。"""
    slots = {}
    for day, dow, periods in DAYS:
        for p in range(1, periods + 1):
            k = (day, p)
            if k in EVENTS:
                slots[k] = (EVENTS[k][0], '行事')
            elif k in BUNKA_FIXED:
                slots[k] = (BUNKA_FIXED[k], '分科確定')
            elif k in GRADE_ALIGN:
                slots[k] = (GRADE_ALIGN[k], '学年合わせ')
            elif k in KATEI and k not in ADJUST:
                slots[k] = ('家庭', '学年合わせ')
            elif k in RIKA_MOVE:
                slots[k] = ('理科', '分科振替')
            elif k in ADJUST:
                slots[k] = (ADJUST[k][0], '調整')
            else:
                sub = BASE[dow][p - 1]
                if sub is None:
                    raise AssertionError('%d日%d校時に基本パターンがありません' % k)
                if sub in ('外国語', '家庭', '総合', '体育'):
                    raise AssertionError(
                        '%d日%d校時: 基本パターンの%sは上の層で確定させる教科。調整表で埋めること'
                        % (day, p, sub))
                slots[k] = (sub, '分科' if sub in ('理科', '書写') else '前月パターン')
    return slots


def tally(slots):
    counts = {}
    for sub, _ in slots.values():
        counts[sub] = counts.get(sub, 0) + 1
    return counts


